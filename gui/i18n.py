def _replace_words(text: str, mapping: dict[str, str]) -> str:
    if not mapping:
        return text
    pattern = re.compile(r"\b(" + "|".join(sorted((re.escape(key) for key in mapping), key=len, reverse=True)) + r")\b", re.IGNORECASE)

    def replace(match: re.Match[str]) -> str:
        source = match.group(0)
        target = mapping.get(source.lower(), source)
        if source.isupper():
            return target.upper()
        if source[:1].isupper():
            return target[:1].upper() + target[1:]
        return target

    return pattern.sub(replace, text)


def _dictionary(language: str) -> dict[str, str]:
    return EN if language == "en" else PT_BR if language == "pt_BR" else {}


def tr(text: Any, language: Any = None) -> str:
    source = str(text if text is not None else "")
    lang = normalize_language(language if language is not None else _current_language)
    if lang == "es" or not source:
        return source
    table = _dictionary(lang)
    if source in table:
        return table[source]
    if "\n" in source:
        return "\n".join(tr(line, lang) for line in source.split("\n"))

    # Iconos y numeración pueden preceder a una etiqueta traducible.
    match = re.match(r"^([^A-Za-zÁÉÍÓÚÜÑáéíóúüñ¿¡]*)(.+)$", source)
    if match and match.group(1) and match.group(2) in table:
        return match.group(1) + table[match.group(2)]

    dynamic = source
    replacements = EN_REPLACEMENTS if lang == "en" else PT_REPLACEMENTS
    for original, translated in sorted(replacements.items(), key=lambda item: len(item[0]), reverse=True):
        dynamic = dynamic.replace(original, translated)
    word_map = WORD_MAP_EN if lang == "en" else WORD_MAP_PT
    return _replace_words(dynamic, word_map)


def _translate_property(widget: QWidget, prop: str, getter: Any, setter: Any, language: str) -> None:
    key = f"_nikaido_i18n_{prop}_source"
    source = widget.property(key)
    current = str(getter() or "")
    if source is None:
        source = current
        widget.setProperty(key, source)
    setter(tr(source, language))


def mark_text_source(widget: QWidget, source: str, *, tooltip: str | None = None) -> None:
    widget.setProperty("_nikaido_i18n_text_source", str(source))
    if tooltip is not None:
        widget.setProperty("_nikaido_i18n_tooltip_source", str(tooltip))


def _iter_widgets(root: QWidget) -> Iterable[QWidget]:
    yield root
    yield from root.findChildren(QWidget)


def translate_widget_tree(root: QWidget, language: Any = None) -> None:
    """Traduce widgets existentes sin reconstruir la interfaz ni sus motores."""
    lang = normalize_language(language if language is not None else _current_language)
    for widget in _iter_widgets(root):
        if hasattr(widget, "windowTitle") and hasattr(widget, "setWindowTitle"):
            title = str(widget.windowTitle() or "")
            if title:
                _translate_property(widget, "window_title", widget.windowTitle, widget.setWindowTitle, lang)
        tooltip = str(widget.toolTip() or "")
        if tooltip:
            _translate_property(widget, "tooltip", widget.toolTip, widget.setToolTip, lang)
        accessible = str(widget.accessibleName() or "")
        if accessible:
            _translate_property(widget, "accessible", widget.accessibleName, widget.setAccessibleName, lang)

        if isinstance(widget, (QLabel, QAbstractButton)) and not bool(widget.property("i18nSkipText")):
            _translate_property(widget, "text", widget.text, widget.setText, lang)
        elif isinstance(widget, QGroupBox):
            _translate_property(widget, "title", widget.title, widget.setTitle, lang)
        elif isinstance(widget, QLineEdit):
            placeholder = widget.placeholderText()
            if placeholder:
                _translate_property(
                    widget, "placeholder", widget.placeholderText, widget.setPlaceholderText, lang
                )

        if isinstance(widget, QComboBox) and not bool(widget.property("i18nSkipItems")):
            sources = widget.property("_nikaido_i18n_combo_sources")
            if not isinstance(sources, list) or len(sources) != widget.count():
                sources = [widget.itemText(i) for i in range(widget.count())]
                widget.setProperty("_nikaido_i18n_combo_sources", sources)
            blocked = widget.blockSignals(True)
            try:
                for index, source in enumerate(sources):
                    widget.setItemText(index, tr(source, lang))
            finally:
                widget.blockSignals(blocked)

        if isinstance(widget, QTabWidget):
            sources = widget.property("_nikaido_i18n_tab_sources")
            if not isinstance(sources, list) or len(sources) != widget.count():
                sources = [widget.tabText(i) for i in range(widget.count())]
                widget.setProperty("_nikaido_i18n_tab_sources", sources)
            for index, source in enumerate(sources):
                widget.setTabText(index, tr(source, lang))

        if isinstance(widget, QTableWidget):
            headers = widget.property("_nikaido_i18n_header_sources")
            if not isinstance(headers, list) or len(headers) != widget.columnCount():
                headers = [
                    widget.horizontalHeaderItem(i).text() if widget.horizontalHeaderItem(i) else ""
                    for i in range(widget.columnCount())
                ]
                widget.setProperty("_nikaido_i18n_header_sources", headers)
            for index, source in enumerate(headers):
                item = widget.horizontalHeaderItem(index)
                if item is not None:
                    item.setText(tr(source, lang))

    # QAction no hereda de QWidget.
    for menu in root.findChildren(QMenu):
        for action in menu.actions():
            if not isinstance(action, QAction):
                continue
            source = action.property("_nikaido_i18n_text_source")
            if source is None:
                source = action.text()
                action.setProperty("_nikaido_i18n_text_source", source)
            action.setText(tr(source, lang))
