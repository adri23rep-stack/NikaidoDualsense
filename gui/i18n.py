_current_language = "es"


def normalize_language(value: Any) -> str:
    raw = str(value or "es").strip().replace("-", "_").lower()
    if raw in {"en", "en_us", "english"}:
        return "en"
    if raw in {"pt", "pt_br", "ptbr", "portuguese", "português"}:
        return "pt_BR"
    return "es"


def set_current_language(value: Any) -> str:
    global _current_language
    _current_language = normalize_language(value)
    return _current_language


def current_language() -> str:
    return _current_language


